#pragma once

#include "build.h"
#include "common_game.h"
#include "controls.h"

// Bots are ordinary player slots. Their input is generated by the host (or
// the local game) and goes through the same FIFO as human input, so every
// peer simulates them exactly like remote humans.

enum
{
    kBotSkillMin = 0,
    kBotSkillMax = 4,
    kBotSkillDefault = 2,
};

// Requested bot setup. Applied when the next BloodBath/Teams level starts.
extern int32_t gBotCount;
extern int32_t gBotSkill;
// Debug: let the AI drive the local player too (bot-versus-bot smoke tests).
extern int32_t gBotAutopilot;
extern int32_t gBotDebug;

// Bit n set: slot n is occupied by a bot in the current game. Identical on
// all peers, derived from the start-game packet.
extern uint8_t gBotSlots;

inline bool botIsBot(int nPlayer)
{
    return (unsigned)nPlayer < kMaxPlayers && (gBotSlots & (1 << nPlayer)) != 0;
}

// Pack/unpack the bot setup carried by PKT_STARTGAME.
int botPackStartInfo(void);
// Returns true when the start packet requests bots.
bool botStartInfoHasBots(int nInfo);

// Called by StartLevel before players are initialized: rebuilds the bot part
// of the connect list from the start-game info. Every peer does the same.
void botSetupSlots(int nInfo);
// Called by StartLevel after players are spawned: resets per-level AI state.
void botLevelInit(void);
// Host only: put this frame's input for every bot into the FIFO.
void botGenerateInputs(void);
// bot_autopilot: replace the local player's input with the AI's.
void botAutopilotInput(GINPUT *pInput);
// Remove all bot slots (leaving a game, returning to single player).
void botClearSlots(void);

void botInitCommands(void);
